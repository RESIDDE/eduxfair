// Builds the paste-able schema bundle, and proves it applies.
//
// Applying the schema to a hosted Supabase project needs either the database
// password, a personal access token, or the SQL editor. The editor is the only
// one of the three that needs no extra credential, and it takes one script —
// so the 24 migrations get concatenated into one file.
//
// The concatenation is the risky part. The dev server applies migrations one
// file at a time, each in its own implicit transaction; the SQL editor runs the
// lot as a single script. A dollar-quoted block that happens to work per-file,
// or an ordering that only holds because of the per-file boundary, would fail
// there and nowhere else. So this generates the bundle and then applies it the
// way the editor would, to a fresh database.
//
//   node bundle-migrations.mjs
//
// The shim supplies what a real Supabase project already has — the auth and
// storage schemas, auth.uid(), the three roles — so what is being tested here
// is the project's own 24 migrations, not Supabase itself.

import { PGlite } from '@electric-sql/pglite';
import { btree_gist } from '@electric-sql/pglite/contrib/btree_gist';
import { citext } from '@electric-sql/pglite/contrib/citext';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { basename, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const migrationsDir = join(root, 'supabase', 'migrations');
const outPath = join(root, 'supabase', 'apply_all_migrations.sql');

const green = (s) => `\x1b[32m${s}\x1b[0m`;
const red = (s) => `\x1b[31m${s}\x1b[0m`;
const dim = (s) => `\x1b[2m${s}\x1b[0m`;

const HEADER = `-- Lekkside Connect — the whole schema, in migration order.
--
-- GENERATED by devserver/bundle-migrations.mjs. Do not edit: edit the
-- migrations in supabase/migrations/ and regenerate, or the two will disagree
-- about what production runs.
--
-- It exists for one job: applying the schema by pasting into the Supabase SQL
-- editor, which is the only route that needs no credential beyond a login.
--
-- Run it ONCE, on a project with no Lekkside schema. It is deliberately not
-- re-runnable — \`create type\`, \`create policy\` and
-- \`alter publication ... add table\` each fail when the object already exists,
-- which is right for a migration and awkward for a paste. If it stops halfway,
-- fix the cause and start from a clean project rather than re-running.
--
-- Do NOT also run supabase/seed.sql: that is the demo fixture, 70 invented
-- students and 3 invented universities. The whole point of a live project is
-- that everything on a screen was put there by a real person.
`;

// `--from 20251010000025` writes out only the migrations at or after that
// filename. Needed once a project has had the full bundle applied: re-running
// it would fail on the first `create type` that already exists, so a follow-up
// goes out as a delta. Verification below still applies the *whole* set, since
// a delta on its own says nothing about whether it composes.
const fromArg = (() => {
  const i = process.argv.indexOf('--from');
  return i === -1 ? null : process.argv[i + 1];
})();

async function build() {
  const all = (await readdir(migrationsDir))
    .filter((f) => f.endsWith('.sql'))
    .sort();
  const names = fromArg ? all.filter((f) => f >= fromArg) : all;

  if (names.length === 0) {
    console.error(`\nNo migrations at or after ${fromArg}.\n`);
    process.exit(1);
  }

  const parts = [HEADER];
  for (const name of names) {
    const body = await readFile(join(migrationsDir, name), 'utf8');
    parts.push(
      `\n\n-- ${'='.repeat(72)}\n-- ${name}\n-- ${'='.repeat(72)}\n\n` +
        `${body.trimEnd()}\n`,
    );
  }
  const fullParts = [];
  for (const name of all) {
    fullParts.push(await readFile(join(migrationsDir, name), 'utf8'), '\n');
  }

  return {
    bundle: parts.join(''),
    full: fullParts.join(''),
    count: names.length,
    names,
  };
}

async function verify(bundle) {
  const db = new PGlite({ extensions: { btree_gist, citext } });
  await db.waitReady;

  // What a real Supabase project already provides.
  for (const f of [
    join(root, 'supabase', 'tests', '00_supabase_shim.sql'),
    join(here, 'shim_extra.sql'),
  ]) {
    await db.exec(await readFile(f, 'utf8'));
  }
  // Real Supabase ships this publication, and the shim already creates it if
  // absent — so nothing to do here. Noted because two migrations do
  // `alter publication supabase_realtime add table ...`, which needs it to
  // exist and is the kind of dependency that is invisible until it is missing.

  // Undo the shim's blanket default privileges before applying the bundle.
  //
  // The shim grants them so that an RLS test fails on a policy rather than on
  // a missing GRANT, which is right for the RLS suite. But it also means every
  // table silently inherits privileges the migrations never asked for — and
  // that is exactly how this schema reached a real project with 50 tables, RLS
  // on, 163 policies, and `42501 permission denied` on every single one.
  //
  // Here the migrations have to grant for themselves, as they must in
  // production.
  await db.exec(`
    alter default privileges in schema public
      revoke select, insert, update, delete on tables
      from anon, authenticated, service_role;
    alter default privileges in schema public
      revoke usage, select on sequences
      from anon, authenticated, service_role;
    alter default privileges in schema public
      revoke execute on functions
      from anon, authenticated, service_role;
  `);

  await db.exec(bundle);

  const one = async (sql) => Number((await db.query(sql)).rows[0].n);
  const stats = {
    tables: await one(`select count(*) as n from information_schema.tables
                        where table_schema = 'public' and table_type = 'BASE TABLE'`),
    views: await one(`select count(*) as n from information_schema.views
                       where table_schema = 'public'`),
    functions: await one(`select count(*) as n from pg_proc p
                            join pg_namespace n on n.oid = p.pronamespace
                           where n.nspname = 'public'`),
    policies: await one(`select count(*) as n from pg_policies
                          where schemaname = 'public'`),
    buckets: await one('select count(*) as n from storage.buckets'),
  };

  // A public table with RLS off is readable by anyone holding the anon key,
  // which is shipped in the app. That is the one schema mistake that cannot be
  // caught by any amount of client testing.
  const unprotected = (
    await db.query(`select t.tablename from pg_tables t
                      join pg_class c on c.relname = t.tablename
                     where t.schemaname = 'public' and not c.relrowsecurity
                     order by 1`)
  ).rows.map((r) => r.tablename);

  // A table PostgREST cannot reach is invisible however good its policies are.
  const unreachable = (
    await db.query(`
      select t.tablename,
             has_table_privilege('anon',          'public.'||t.tablename, 'SELECT') as anon_select,
             has_table_privilege('authenticated', 'public.'||t.tablename, 'SELECT') as auth_select,
             has_table_privilege('authenticated', 'public.'||t.tablename, 'INSERT') as auth_insert
        from pg_tables t
       where t.schemaname = 'public'
       order by 1`)
  ).rows.filter((r) => !r.anon_select || !r.auth_select || !r.auth_insert)
        .map((r) => r.tablename);

  return { stats, unprotected, unreachable };
}

const { bundle, full, count, names } = await build();
const target = fromArg
  ? join(root, 'supabase', 'apply_pending.sql')
  : outPath;
await writeFile(target, bundle, 'utf8');

console.log(`\nBundled ${count} migration(s) -> supabase/${basename(target)}`);
console.log(dim(`  ${(bundle.length / 1024).toFixed(0)} KiB`));
console.log(dim(`  ${basename(names[0])} … ${basename(names[names.length - 1])}`));

try {
  const { stats, unprotected, unreachable } = await verify(full);
  console.log(`\n  ${green('ok')}  all ${(await readdir(migrationsDir)).filter(f=>f.endsWith('.sql')).length} migrations apply cleanly as one script`);
  console.log(
    dim(
      `      ${stats.tables} tables · ${stats.views} views · ` +
        `${stats.functions} functions · ${stats.policies} policies · ` +
        `${stats.buckets} storage buckets`,
    ),
  );

  if (unreachable.length > 0) {
    console.log(`  ${red('FAIL')}  tables the API roles hold no privileges on: ` +
      unreachable.join(', '));
    console.log(red('\nThe schema would apply and then be unreachable.\n'));
    process.exit(1);
  }
  console.log(`  ${green('ok')}  every table is reachable by the API roles`);

  if (unprotected.length > 0) {
    console.log(`  ${red('FAIL')}  public tables with RLS disabled: ` +
      unprotected.join(', '));
    console.log(red('\nRefusing to call this bundle good.\n'));
    process.exit(1);
  }
  console.log(`  ${green('ok')}  every public table has RLS enabled`);
  console.log(green('\nSafe to paste into the SQL editor.\n'));
  process.exit(0);
} catch (err) {
  console.log(`\n  ${red('FAIL')}  the bundle does not apply: ${err.message}`);
  if (err.detail) console.log(red(`      detail: ${err.detail}`));
  if (err.hint) console.log(red(`      hint:   ${err.hint}`));
  console.log(red('\nDo not paste this.\n'));
  process.exit(1);
}
