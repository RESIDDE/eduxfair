import 'package:flutter/foundation.dart';

import '../../../core/supabase/supabase_service.dart';
import '../models/fair.dart';

/// The Fair Passport: registering for an event, showing the QR, and reading
/// the report afterwards.
///
/// The student never records a booth visit — only institution staff can, via
/// `record_booth_visit()`, which checks the pass code and that the scanner
/// actually staffs that booth. There is no insert policy on `booth_visits` at
/// all, so this provider only reads them.
class FairsProvider extends ChangeNotifier {
  final _service = SupabaseService.instance;

  List<Fair> _fairs = [];
  List<FairRegistration> _registrations = [];
  List<BoothVisit> _visits = [];
  bool _loading = false;
  bool _busy = false;
  String? _error;

  List<Fair> get fairs => _fairs;
  List<FairRegistration> get registrations => _registrations;
  List<BoothVisit> get visits => _visits;
  bool get loading => _loading;
  bool get busy => _busy;
  String? get error => _error;

  /// The event to lead with: one happening now, else the next one.
  FairRegistration? get currentRegistration {
    final live = _registrations
        .where((r) => r.fair?.isOnNow ?? false)
        .toList();
    if (live.isNotEmpty) return live.first;

    final upcoming = _registrations
        .where((r) => r.fair?.isUpcoming ?? false)
        .toList()
      ..sort((a, b) => (a.fair?.startsAt ?? DateTime(2100))
          .compareTo(b.fair?.startsAt ?? DateTime(2100)));
    return upcoming.isEmpty ? null : upcoming.first;
  }

  List<Fair> get upcomingFairs =>
      _fairs.where((f) => !f.isOver && f.isActive).toList();

  bool isRegistered(String fairId) =>
      _registrations.any((r) => r.fairId == fairId);

  Future<void> load() async {
    _loading = true;
    _error = null;
    notifyListeners();

    try {
      final results = await Future.wait([
        _fetchFairs(),
        _fetchRegistrations(),
        _fetchVisits(),
      ]);
      _fairs = results[0] as List<Fair>;
      _registrations = results[1] as List<FairRegistration>;
      _visits = results[2] as List<BoothVisit>;
    } catch (e) {
      _error = SupabaseService.describeError(e);
    } finally {
      _loading = false;
      notifyListeners();
    }
  }

  Future<List<Fair>> _fetchFairs() async {
    final rows = await _service.client
        .from('fairs')
        .select()
        .eq('is_active', true)
        .order('starts_at');
    return (rows as List)
        .map((r) => Fair.fromMap(r as Map<String, dynamic>))
        .toList();
  }

  Future<List<FairRegistration>> _fetchRegistrations() async {
    final id = _service.userId;
    if (id == null) return [];
    final rows = await _service.client
        .from('fair_registrations')
        .select('*, fairs!inner(*)')
        .eq('profile_id', id)
        .order('created_at', ascending: false);
    return (rows as List)
        .map((r) => FairRegistration.fromMap(r as Map<String, dynamic>))
        .toList();
  }

  Future<List<BoothVisit>> _fetchVisits() async {
    final id = _service.userId;
    if (id == null) return [];
    final rows = await _service.client
        .from('booth_visits')
        .select('*, fair_exhibitors!inner(booth_label, '
            'institutions!inner(id, name, logo_url)), programs(id, name)')
        .eq('profile_id', id)
        .order('created_at', ascending: false);
    return (rows as List)
        .map((r) => BoothVisit.fromMap(r as Map<String, dynamic>))
        .toList();
  }

  /// Registers for a fair. The pass code is generated by a database trigger,
  /// so it is read back rather than supplied.
  Future<bool> register(String fairId) async {
    _busy = true;
    _error = null;
    notifyListeners();

    try {
      await _service.client.from('fair_registrations').insert({
        'fair_id': fairId,
        'profile_id': _service.userId,
      });
      _registrations = await _fetchRegistrations();
      return true;
    } catch (e) {
      _error = SupabaseService.describeError(e);
      return false;
    } finally {
      _busy = false;
      notifyListeners();
    }
  }

  Future<FairReport?> fetchReport(String fairId) async {
    _error = null;
    try {
      final result = await _service.client.rpc(
        'fair_report',
        params: {'p_fair_id': fairId},
      );
      if (result == null) return null;
      return FairReport.fromJson((result as Map).cast<String, dynamic>());
    } catch (e) {
      _error = SupabaseService.describeError(e);
      notifyListeners();
      return null;
    }
  }

  void clearError() {
    if (_error == null) return;
    _error = null;
    notifyListeners();
  }
}
